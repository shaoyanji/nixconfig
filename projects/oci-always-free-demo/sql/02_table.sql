-- Run as TODO_APP. Safe to re-run.
SET DEFINE ON
WHENEVER SQLERROR EXIT FAILURE

DECLARE
  l_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_exists FROM user_tables WHERE table_name = 'TODOS';
  IF l_exists = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE todos (
      id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      task    VARCHAR2(255) NOT NULL,
      is_done NUMBER(1) DEFAULT 0 NOT NULL
    )';
  END IF;
END;
/

INSERT INTO todos (task, is_done)
SELECT 'Read the README', 0 FROM dual
WHERE NOT EXISTS (SELECT 1 FROM todos);

COMMIT;

EXIT
