"""Always Free to-do demo: Flask + python-oracledb in thin mode against ADB.

The schema password is read from OCI Vault at startup with the instance
principal, so no database credential exists on disk. The mTLS wallet is placed
in /opt/todo/wallet by cloud-init.
"""

import base64
import logging
import os
import threading
import time
from pathlib import Path

import oci
import oracledb
from flask import Flask, redirect, render_template_string, request, url_for

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
LOG = logging.getLogger("todo")

WALLET_DIR = Path(os.environ.get("ADB_WALLET_DIR", "/opt/todo/wallet"))
DB_USER = os.environ.get("ADB_USER", "TODO_APP")
DB_ALIAS = os.environ.get("ADB_TNS_ALIAS", "tododb_low")
PASSWORD_SECRET_OCID = os.environ["ADB_PASSWORD_SECRET_OCID"]
PORT = int(os.environ.get("PORT", "8080"))

DDL = """
CREATE TABLE todos (
  id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task    VARCHAR2(255) NOT NULL,
  is_done NUMBER(1) DEFAULT 0 NOT NULL
)
"""

PAGE = """<!doctype html>
<html lang="en">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Always Free To-Do</title>
<style>
  body { font: 16px/1.5 system-ui, sans-serif; max-width: 38rem; margin: 3rem auto; padding: 0 1rem; color: #1b1b1b; }
  h1 { font-size: 1.4rem; margin-bottom: 1.5rem; }
  form.add { display: flex; gap: .5rem; margin-bottom: 1.5rem; }
  input[name=task] { flex: 1; padding: .5rem .6rem; border: 1px solid #c9c9c9; border-radius: 4px; }
  button { padding: .45rem .8rem; border: 1px solid #c9c9c9; background: #f4f4f4; border-radius: 4px; cursor: pointer; }
  button:hover { background: #e8e8e8; }
  ul { list-style: none; padding: 0; }
  li { display: flex; align-items: center; gap: .5rem; padding: .5rem 0; border-bottom: 1px solid #ececec; }
  li span { flex: 1; }
  li.done span { text-decoration: line-through; color: #8a8a8a; }
  li form { margin: 0; }
  .foot { margin-top: 2rem; color: #8a8a8a; font-size: .8rem; }
</style>
<h1>To-Do</h1>
<form class="add" method="post" action="{{ url_for('add') }}">
  <input name="task" maxlength="255" placeholder="What needs doing?" required autofocus>
  <button type="submit">Add</button>
</form>
<ul>
{% for todo_id, task, is_done in todos %}
  <li class="{{ 'done' if is_done else '' }}">
    <span>{{ task }}</span>
    <form method="post" action="{{ url_for('toggle', todo_id=todo_id) }}">
      <button type="submit">{{ 'Undo' if is_done else 'Done' }}</button>
    </form>
    <form method="post" action="{{ url_for('remove', todo_id=todo_id) }}">
      <button type="submit">Delete</button>
    </form>
  </li>
{% else %}
  <li><span>Nothing yet.</span></li>
{% endfor %}
</ul>
<p class="foot">
  Flask on an Always Free AMD micro, Autonomous Database Always Free (2 ECPU / 20 GB),
  behind a 10 Mbps flexible load balancer. Password read from OCI Vault at runtime.
</p>
</html>
"""

app = Flask(__name__)
_pool = None


def schema_password():
    signer = oci.auth.signers.InstancePrincipalsSecurityTokenSigner()
    client = oci.secrets.SecretsClient({}, signer=signer)
    bundle = client.get_secret_bundle(PASSWORD_SECRET_OCID).data
    return base64.b64decode(bundle.secret_bundle_content.content).decode()


def pool():
    global _pool
    if _pool is None:
        candidate = oracledb.create_pool(
            user=DB_USER,
            password=schema_password(),
            dsn=DB_ALIAS,
            config_dir=str(WALLET_DIR),
            wallet_location=str(WALLET_DIR),
            min=1,
            max=4,
            increment=1,
        )
        with candidate.acquire() as connection:
            try:
                connection.execute(DDL)
            except oracledb.DatabaseError as exc:
                if "ORA-00955" not in str(exc):
                    raise
        _pool = candidate
        LOG.info("connected to %s as %s", DB_ALIAS, DB_USER)
    return _pool


def connect_when_ready():
    for attempt in range(1, 61):
        try:
            pool()
            return
        except Exception as exc:
            LOG.warning("database not ready (attempt %d): %s", attempt, exc)
            time.sleep(10)


@app.get("/")
def index():
    with pool().acquire() as connection:
        todos = connection.execute(
            "SELECT id, task, is_done FROM todos ORDER BY is_done, id DESC"
        ).fetchall()
    return render_template_string(PAGE, todos=todos)


@app.post("/add")
def add():
    task = (request.form.get("task") or "").strip()
    if task:
        with pool().acquire() as connection:
            connection.execute("INSERT INTO todos (task) VALUES (:1)", [task[:255]])
            connection.commit()
    return redirect(url_for("index"), code=303)


@app.post("/toggle/<int:todo_id>")
def toggle(todo_id):
    with pool().acquire() as connection:
        connection.execute("UPDATE todos SET is_done = 1 - is_done WHERE id = :1", [todo_id])
        connection.commit()
    return redirect(url_for("index"), code=303)


@app.post("/delete/<int:todo_id>")
def remove(todo_id):
    with pool().acquire() as connection:
        connection.execute("DELETE FROM todos WHERE id = :1", [todo_id])
        connection.commit()
    return redirect(url_for("index"), code=303)


@app.get("/healthz")
def healthz():
    try:
        with pool().acquire() as connection:
            connection.execute("SELECT 1 FROM dual").fetchone()
    except Exception as exc:
        return {"status": "degraded", "detail": str(exc)[:200]}, 503
    return {"status": "ok"}


if __name__ == "__main__":
    threading.Thread(target=connect_when_ready, daemon=True).start()
    from waitress import serve

    serve(app, host="0.0.0.0", port=PORT)
