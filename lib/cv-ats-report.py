#!/usr/bin/env python3
"""Render the CV ATS audit into one page and one machine-readable document.

The inputs are what `cv-ats-check.sh` printed while the CVs were read back, so
the page cannot describe a different build from the PDFs beside it: both are
inputs of one derivation. A defect fails that derivation, which is why the page
only ever lists CVs that passed — the page is the record, not the gate.
"""
import html
import json
import os
import sys

root = sys.argv[1]
entries = []
for log in sorted(f for f in os.listdir(root) if f.endswith(".log")):
    with open(os.path.join(root, log), encoding="utf-8") as fh:
        output = fh.read().strip()
    entries.append(
        {
            "cv": log[: -len(".log")],
            "ok": output.endswith("matches the record"),
            "output": output,
        }
    )

plural = "" if len(entries) == 1 else "s"
sections = "".join(
    "<section><h2>{cv} <span class=\"{cls}\">{verdict}</span></h2>"
    "<pre>{output}</pre></section>\n".format(
        cv=html.escape(e["cv"]),
        cls="ok" if e["ok"] else "bad",
        verdict="pass" if e["ok"] else "defect",
        output=html.escape(e["output"]),
    )
    for e in entries
)

page = """<!doctype html>
<html lang="en">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>CV ATS audit</title>
<style>
:root { color-scheme: light }
body { margin: 0; padding: 3rem 1.5rem; background: #f6f2e9; color: #14120e;
  font: 15px/1.55 ui-monospace, SFMono-Regular, Menlo, monospace; }
main { max-width: 60rem; margin: 0 auto }
h1 { font-size: 1.5rem; margin: 0 0 .3rem }
p.lede { color: #6a6355; margin: 0 0 2rem; max-width: 48rem }
section { border-left: 3px solid #1c5f4d; padding: .2rem 0 .2rem 1rem; margin: 0 0 1.6rem }
h2 { font-size: 1rem; margin: .2rem 0 .5rem; font-weight: 600 }
.ok { color: #1c5f4d } .bad { color: #a03024 }
pre { margin: 0; white-space: pre-wrap; color: #3a3630 }
a { color: #1c5f4d }
</style>
<main>
<h1>CV ATS audit</h1>
<p class="lede">__COUNT__ shipped CV__PLURAL__, read back with <code>pdftotext</code> against the
record that built each one: headings in the order a parser looks for them, every role, project,
degree and skill group, the name first, contact in the body, URLs visible as text, and no
hyphenated line end. Generated by <code>.#sites.cv-ats-site</code>; a defect fails that build,
so only passing CVs appear here. <a href="https://matt.bountystash.com/">matt.bountystash.com</a></p>
__SECTIONS__</main>
"""
page = (
    page.replace("__COUNT__", str(len(entries)))
    .replace("__PLURAL__", plural)
    .replace("__SECTIONS__", sections)
)

with open(os.path.join(root, "index.html"), "w", encoding="utf-8") as fh:
    fh.write(page)
with open(os.path.join(root, "report.json"), "w", encoding="utf-8") as fh:
    json.dump({"ok": all(e["ok"] for e in entries), "checks": entries}, fh, indent=2, sort_keys=True)
    fh.write("\n")
print(
    "cv-ats-report: {ok}/{total} CV(s) match their records".format(
        ok=sum(1 for e in entries if e["ok"]), total=len(entries)
    )
)
